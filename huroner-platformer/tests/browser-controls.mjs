import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs';
fs.mkdirSync('test-results', { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH, headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 844, height: 390 }, hasTouch: true });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
const url = process.env.BASE_URL || 'http://127.0.0.1:8123/huroner-platformer/dist/?qa=1';
const load = async () => { await page.goto(url); await page.waitForFunction(() => window.__ferretQA); };
const controls = () => page.evaluate(() => ({ axis: window.__ferretQA.scene.controls.axis, jump: window.__ferretQA.scene.controls.jump }));
const state = () => page.evaluate(() => window.__ferretQA.state());
const cdp = await page.context().newCDPSession(page);
await cdp.send('Emulation.setTouchEmulationEnabled', { enabled: true, maxTouchPoints: 5 });
const touch = (type, touchPoints) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints });
const center = selector => page.locator(selector).boundingBox().then(r => ({ x: r.x + r.width / 2, y: r.y + r.height / 2 }));
try {
    await load();
    await page.click('#open-settings');
    assert(await page.locator('[value="swipe"]').isChecked());
    await page.screenshot({ path: 'test-results/controls-settings.png' });
    await page.keyboard.press('Escape');
    assert(!await page.locator('#settings').isVisible());
    await page.click('#start');
    assert(await page.locator('#swipe-zone').isVisible());
    assert(!await page.locator('#directions').isVisible());
    const origin = { ...await center('#swipe-zone'), id: 1 };
    const jump = { ...await center('[data-control="jump"]'), id: 2 };
    await touch('touchStart', [origin]);
    await touch('touchMove', [{ ...origin, y: origin.y - 45 }]);
    assert.deepEqual(await controls(), { axis: 0, jump: false }, 'vertical drag does not move or jump');
    await touch('touchMove', [{ ...origin, x: origin.x + 6 }]);
    assert.equal((await controls()).axis, 0, 'dead zone');
    const right = { ...origin, x: origin.x + 48 };
    const before = await state();
    await touch('touchMove', [right]);
    await page.waitForTimeout(200);
    assert.equal((await controls()).axis, 1);
    assert((await state()).player.x > before.player.x, 'swipe moves player');
    await touch('touchStart', [right, jump]);
    await page.waitForTimeout(120);
    assert.deepEqual(await controls(), { axis: 1, jump: true });
    assert((await state()).player.vy < 0, 'jump works with swipe');
    await touch('touchEnd', [jump]);
    assert.deepEqual(await controls(), { axis: 1, jump: false });
    await touch('touchMove', [{ ...origin, x: origin.x - 48 }]);
    await page.waitForTimeout(220);
    assert.equal((await controls()).axis, -1);
    assert((await state()).player.vx < 0, 'reverse direction');
    await touch('touchEnd', []);
    await page.waitForTimeout(250);
    assert.equal((await controls()).axis, 0);
    assert.equal((await state()).player.vx, 0, 'release stops player');
    await touch('touchStart', [origin]);
    await touch('touchMove', [{ ...origin, x: 500 }]);
    assert.equal((await controls()).axis, 1, 'pointer capture outside zone');
    await touch('touchCancel', []);
    assert.equal((await controls()).axis, 0, 'cancel resets');
    await touch('touchStart', [origin]);
    await touch('touchMove', [right]);
    await page.keyboard.press('p');
    assert.equal((await state()).mode, 'paused');
    assert.equal((await controls()).axis, 0, 'pause clears swipe');
    await touch('touchEnd', []);
    await page.click('#resume');
    await page.keyboard.down('ArrowRight');
    assert.equal((await controls()).axis, 1, 'keyboard works with swipe');
    await page.keyboard.up('ArrowRight');
    await page.screenshot({ path: 'test-results/controls-swipe-mobile.png' });
    await load();
    await page.click('#open-settings');
    await page.check('[value="buttons"]');
    await page.click('#close-settings');
    await load();
    await page.click('#open-settings');
    assert(await page.locator('[value="buttons"]').isChecked(), 'setting persists');
    await page.click('#close-settings');
    await page.click('#start');
    assert(await page.locator('#directions').isVisible());
    assert(!await page.locator('#swipe-zone').isVisible());
    await page.waitForFunction(() => window.__ferretQA.state().player.grounded);
    const rightButton = { ...await center('[data-control="right"]'), id: 1 };
    await touch('touchStart', [rightButton, jump]);
    await page.waitForTimeout(120);
    assert.deepEqual(await controls(), { axis: 1, jump: true });
    assert((await state()).player.vx > 0 && (await state()).player.vy < 0);
    await touch('touchEnd', []);
    assert.deepEqual(await controls(), { axis: 0, jump: false });
    for (const [width, height] of [[667, 375], [844, 390], [932, 430], [1280, 720]]) {
        await page.setViewportSize({ width, height });
        const rects = await page.locator('[data-control]').evaluateAll(buttons => buttons.map(b => {
            const r = b.getBoundingClientRect(); return { x: r.x, y: r.y, w: r.width, h: r.height, right: r.right, bottom: r.bottom };
        }));
        assert(rects.every(r => r.x >= 0 && r.y >= 0 && r.right <= width && r.bottom <= height));
        assert(rects.slice(0, 2).every(r => r.w >= 88 && r.h >= 80), 'larger movement buttons');
        assert(rects[1].right < rects[2].x, 'movement and jump do not overlap');
    }
    await page.setViewportSize({ width: 844, height: 390 });
    await page.screenshot({ path: 'test-results/controls-buttons-mobile.png' });
    await page.evaluate(() => localStorage.setItem('ferret-jump-controls-v1', 'invalid'));
    await load();
    await page.click('#start');
    assert(await page.locator('#swipe-zone').isVisible(), 'invalid preference defaults to swipe');
    await page.addInitScript(() => {
        Storage.prototype.getItem = () => { throw new Error('storage blocked'); };
        Storage.prototype.setItem = () => { throw new Error('storage blocked'); };
    });
    await load();
    await page.click('#open-settings');
    assert(await page.locator('[value="swipe"]').isChecked());
    await page.check('[value="buttons"]');
    await page.click('#close-settings');
    await page.click('#start');
    assert(await page.locator('#directions').isVisible(), 'blocked storage remains usable');
    assert.deepEqual(errors, []);
    console.log('PASS: default, settings, persistence, horizontal swipe, multitouch jump, reverse, release, capture, cancel, pause, keyboard, larger buttons, viewports, invalid/blocked storage; Chromium touch emulation.');
} finally { await browser.close(); }
